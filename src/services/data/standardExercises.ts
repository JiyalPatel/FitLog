export function searchStandardExercises(
  query: string,
  muscleGroup?: MuscleGroup | 'All'
): StandardExercise[] {
  let list = STANDARD_EXERCISES;

  if (muscleGroup && muscleGroup !== 'All') {
    if (muscleGroup === 'Arms') {
      // Support legacy 'Arms' filter: match Biceps, Triceps, Forearms, or Arms
      list = list.filter(
        (ex) =>
          ex.muscleGroup === 'Biceps' ||
          ex.muscleGroup === 'Triceps' ||
          ex.muscleGroup === 'Forearms' ||
          ex.muscleGroup === 'Arms'
      );
    } else {
      list = list.filter((ex) => ex.muscleGroup === muscleGroup);
    }
  }

  if (query && query.trim()) {
    const q = query.toLowerCase().trim();
    list = list.filter((ex) => {
      const nameMatch = ex.name.toLowerCase().includes(q);
      const muscleMatch = ex.muscleGroup.toLowerCase().includes(q);
      const descMatch = ex.description ? ex.description.toLowerCase().includes(q) : false;

      // Also support search aliases (e.g., "shrug" matches trap movements, "arm" matches biceps/triceps)
      const aliasMatch =
        (q === 'arm' || q === 'arms') &&
        (ex.muscleGroup === 'Biceps' || ex.muscleGroup === 'Triceps' || ex.muscleGroup === 'Forearms');

      const trapMatch =
        (q === 'trap' || q === 'traps' || q === 'shrug' || q === 'shrugs') &&
        ex.name.toLowerCase().includes('shrug');

      return nameMatch || muscleMatch || descMatch || aliasMatch || trapMatch;
    });
  }

  return list;
}
